export type SwMessageType = (typeof MSG)[keyof typeof MSG];

export type SwMessage = {
  type: string;
  [key: string]: unknown;
};

const MSG_VALUES = new Set<string>(Object.values(MSG));

export function isKnownSwMessageType(type: unknown): type is SwMessageType {
  return typeof type === 'string' && MSG_VALUES.has(type);
}

export function isSwMessage(message: unknown): message is SwMessage {
  return Boolean(
    message &&
      typeof message === 'object' &&
      typeof (message as SwMessage).type === 'string'
  );
}
